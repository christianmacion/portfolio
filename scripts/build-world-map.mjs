/**
 * build-world-map.mjs — prebuild Natural Earth 50m → SVG path strings.
 *
 * Reads /node_modules/world-atlas/countries-50m.json, converts TopoJSON
 * → GeoJSON via topojson-client, projects each country via d3-geo
 * geoEquirectangular to a 1080×540 SVG AND via geoOrthographic to a
 * 600×600 globe SVG, and writes the result as a static TypeScript
 * module at src/data/world-map-paths.ts.
 *
 * The output has TWO projection sets:
 *   - d: equirectangular 2:1 path (flat map fallback)
 *   - dGlobe: orthographic 600×600 path (globe view); empty string
 *     when the country is entirely on the back hemisphere from the
 *     chosen center (lon=−30°, lat=15° — frames Eurasia/Africa)
 *
 * Threshold/id filter: Antarctica (ISO 010) is dropped by default —
 * the empty southern hemisphere is cleaner without it.
 *
 * Run: `node scripts/build-world-map.mjs`
 */
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { resolve, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';
import { feature } from 'topojson-client';
import { geoEquirectangular, geoOrthographic, geoPath, geoCentroid } from 'd3-geo';

const __dirname = dirname(fileURLToPath(import.meta.url));
const ROOT = resolve(__dirname, '..');

// === Config ==================================================================
const VIEW_W = 1080;
const VIEW_H = 540;
const GLOBE_SIZE = 600;
const GLOBE_CENTER = [-30, 15]; // [lon, lat] — frames Eurasia / Africa
const SOURCE = resolve(ROOT, 'node_modules/world-atlas/countries-50m.json');
const OUT = resolve(ROOT, 'src/data/world-map-paths.ts');

// === Read + convert =========================================================
const topo = JSON.parse(readFileSync(SOURCE, 'utf8'));
const geo = feature(topo, topo.objects.countries);

// === Project: equirectangular ===============================================
const projection = geoEquirectangular().fitSize([VIEW_W, VIEW_H], geo);
const path = geoPath(projection);

// === Project: orthographic globe ===========================================
const globeProj = geoOrthographic()
  .rotate([-GLOBE_CENTER[0], -GLOBE_CENTER[1], 0])
  .clipAngle(90)
  .fitExtent(
    [[(GLOBE_SIZE - 2 * GLOBE_SIZE / 2.4) / 2, (GLOBE_SIZE - 2 * GLOBE_SIZE / 2.4) / 2], [GLOBE_SIZE, GLOBE_SIZE]],
    { type: 'Sphere' },
  );
const globePath = geoPath(globeProj);

const countries = geo.features.map((f) => {
  const d = path(f) || '';
  // Globe: render the country if it has any visible portion. The d3
  // geoPath will produce null if the entire country is clipped; if
  // it produces a path, we keep it. Partial-overlap is fine.
  const dGlobe = globePath(f) || '';
  const [lon, lat] = geoCentroid(f);
  return {
    id: f.id || '',
    name: f.properties?.name || '',
    lat: Number(lat.toFixed(4)),
    lon: Number(lon.toFixed(4)),
    d,
    dGlobe,
  };
}).filter((c) => c.d.length > 0 && c.id !== '010');

// === Sphere outline (for globe clip) ========================================
const sphereOutline = globePath({ type: 'Sphere' }) || '';

// === Emit TS module =========================================================
mkdirSync(dirname(OUT), { recursive: true });

const header = `/**
 * world-map-paths.ts — prebuilt Natural Earth 50m country paths.
 *
 * GENERATED by scripts/build-world-map.mjs — do not edit by hand.
 * Re-run \`node scripts/build-world-map.mjs\` if the source dataset
 * changes.
 *
 * Equirectangular projection: 1080×540 2:1 viewBox — flat-map fallback.
 * Orthographic globe projection: ${GLOBE_SIZE}×${GLOBE_SIZE} centered on
 * [${GLOBE_CENTER[0]}°, ${GLOBE_CENTER[1]}°] — frames Eurasia/Africa.
 *
 * countries[]: { id (ISO 3166-1 numeric, padded to 3 digits), name, lat, lon, d, dGlobe }
 *   - d: SVG path for the country in equirectangular projection (flat map)
 *   - dGlobe: SVG path for the country in orthographic projection; '' if clipped
 *   - Antarctica (ISO 010) is dropped — empty southern hemisphere is cleaner
 *   - Total ~177 countries
 */
export const MAP_WIDTH = ${VIEW_W};
export const MAP_HEIGHT = ${VIEW_H};
export const GLOBE_VIEW = ${GLOBE_SIZE};
export const GLOBE_CENTER: [number, number] = [${GLOBE_CENTER[0]}, ${GLOBE_CENTER[1]}];
export const GLOBE_SPHERE_D = ${JSON.stringify(sphereOutline)};
export const countries: { id: string; name: string; lat: number; lon: number; d: string; dGlobe: string }[] = ${JSON.stringify(countries, null, 2)};
`;

writeFileSync(OUT, header, 'utf8');
console.log(`[build-world-map] wrote ${countries.length} countries → ${OUT}`);
console.log(`[build-world-map] equirectangular: ${VIEW_W}×${VIEW_H}`);
console.log(`[build-world-map] orthographic globe: ${GLOBE_SIZE}×${GLOBE_SIZE} center=[${GLOBE_CENTER[0]}, ${GLOBE_CENTER[1]}]`);
