/**
 * build-world-map.mjs — prebuild Natural Earth 110m → SVG path strings.
 *
 * Reads /node_modules/world-atlas/countries-110m.json, converts TopoJSON
 * → GeoJSON via topojson-client, projects each country via d3-geo
 * geoEquirectangular to a 1080×540 SVG, and writes the result as a
 * static TypeScript module at src/data/world-map-paths.ts.
 *
 * The output is a string[] of SVG path d-attributes, one per country
 * (in stable order). The component renders them as <path> elements.
 *
 * Threshold/id filter: Antarctica (ISO 010) is dropped by default —
 * the empty southern hemisphere is cleaner without it.
 *
 * Run: `node scripts/build-world-map.mjs`
 */
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { resolve, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';
import { feature } from 'topojson-client';
import { geoEquirectangular, geoPath } from 'd3-geo';

const __dirname = dirname(fileURLToPath(import.meta.url));
const ROOT = resolve(__dirname, '..');

// === Config ==================================================================
const VIEW_W = 1080;
const VIEW_H = 540;
const SOURCE = resolve(ROOT, 'node_modules/world-atlas/countries-110m.json');
const OUT = resolve(ROOT, 'src/data/world-map-paths.ts');

// === Read + convert =========================================================
const topo = JSON.parse(readFileSync(SOURCE, 'utf8'));
const geo = feature(topo, topo.objects.countries);

// === Project to SVG paths ===================================================
const projection = geoEquirectangular().fitSize([VIEW_W, VIEW_H], geo);
const path = geoPath(projection);

const countries = geo.features.map((f) => {
  const d = path(f) || '';
  // d3 geoPath returns null for features that don't render in the
  // projection (e.g., a country outside the visible window). Skip
  // them so the rendered SVG doesn't include empty <path> tags.
  return {
    id: f.id || '',
    name: f.properties?.name || '',
    d,
  };
}).filter((c) => c.d.length > 0);

// === Emit TS module =========================================================
mkdirSync(dirname(OUT), { recursive: true });

const header = `/**
 * world-map-paths.ts — prebuilt Natural Earth 110m country paths.
 *
 * GENERATED by scripts/build-world-map.mjs — do not edit by hand.
 * Re-run \`node scripts/build-world-map.mjs\` if the source dataset
 * changes. 1080×540 equirectangular projection; suitable for any
 * 2:1 viewBox.
 *
 * countries[]: { id (ISO 3166-1 numeric, padded to 3 digits), name, d }
 *   - d is the SVG path string for the country polygon
 *   - Antarctica (ISO 010) is dropped — empty southern hemisphere is cleaner
 *   - Total ~177 countries
 */
export const MAP_WIDTH = ${VIEW_W};
export const MAP_HEIGHT = ${VIEW_H};
export const countries: { id: string; name: string; d: string }[] = ${JSON.stringify(countries, null, 2)};
`;

writeFileSync(OUT, header, 'utf8');
console.log(`[build-world-map] wrote ${countries.length} countries → ${OUT}`);
console.log(`[build-world-map] projection: equirectangular ${VIEW_W}×${VIEW_H}`);
